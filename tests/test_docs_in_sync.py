def test_catalog_tiers_match_the_documented_split(catalog):
    tier_a = [p["id"] for p in catalog["patterns"] if p["tier"] == "A"]
    tier_b = [p["id"] for p in catalog["patterns"] if p["tier"] == "B"]
    assert tier_a == [f"S{n:02d}" for n in (*range(1, 11), 27, 28, 29)], tier_a
    assert tier_b == [f"S{n:02d}" for n in range(11, 20)], tier_b


def test_sample_report_links_its_refs():
    """Every resolved file:line, detector and commit ref in the sample is one
    click from the code. Shape only — this does not prove the sample is fresh."""
    sample = (ROOT / "examples" / "sample-report.md").read_text()
    link = r"\[`[^`]+`\]\(https://github\.example\.com/acme/fixture/"
    refs = [line for line in sample.splitlines()
            if re.match(r"- _(code|detector|commit)_ ", line)]
    locations = [line for line in sample.splitlines()
                 if re.match(r"\*\*(high|medium|low) confidence\*\* · ", line)]
    assert refs and locations
    unlinked = [line for line in refs if not re.match(r"- _\w+_ " + link, line)]
    unlinked += [line for line in locations if not re.search(r"\*\* · " + link, line)]
    assert not unlinked, "unlinked refs in sample-report.md:\n" + "\n".join(unlinked)


def test_versions_agree():
    plugin = json.loads((ROOT / ".claude-plugin" / "plugin.json").read_text())
    market = json.loads((ROOT / ".claude-plugin" / "marketplace.json").read_text())
    with (ROOT / "pyproject.toml").open("rb") as fh:
        pyproject = tomllib.load(fh)

    entry = next(p for p in market["plugins"] if p["name"] == "thunderstruck")
    versions = {
        "plugin.json": plugin["version"],
        "marketplace.json": entry["version"],
        "pyproject.toml": pyproject["project"]["version"],
    }
    assert len(set(versions.values())) == 1, f"version drift: {versions}"

    changelog = (ROOT / "CHANGELOG.md").read_text()
    match = re.search(r"^##\s*\[?(\d+\.\d+\.\d+)\]?", changelog, re.M)
    assert match, "CHANGELOG.md has no version heading"
    assert match.group(1) == plugin["version"], (
        f"CHANGELOG top entry {match.group(1)} != plugin version {plugin['version']}")


def test_example_profile_parses_and_uses_real_pattern_ids(catalog):
    path = ROOT / "examples" / "thunderstruck.toml.example"
    with path.open("rb") as fh:
        profile = tomllib.load(fh)
    known = {p["id"] for p in catalog["patterns"]}
    for pid in (profile.get("patterns") or {}):
        assert pid in known, f"{path.name} references unknown pattern {pid}"
    for pid, override in (profile.get("patterns") or {}).items():
        if isinstance(override, dict) and "tier" in override:
            assert str(override["tier"]).upper() in {"A", "B", "C"}


