"""Generated artefacts and version numbers must not drift.

The catalog is the single source of truth for what the tool checks. If the
prose a model reads, or the sample a user judges the tool by, disagrees with
it, the documentation is actively misleading.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent


def test_patterns_reference_is_regenerated(plugin_root):
    proc = subprocess.run(
        [sys.executable, str(plugin_root / "scripts" / "gen_catalog_docs.py"), "--check"],
        capture_output=True, text=True)
    assert proc.returncode == 0, (
        proc.stdout + proc.stderr +
        "\nRun: uv run scripts/gen_catalog_docs.py")


